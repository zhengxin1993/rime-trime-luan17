-- ---------------------------------------------------------------------------
-- 共享运行状态（require 缓存同一实例，processor / filter 共用）
--
-- 设计前提（已核对 Trime 3.3.14 + librime + librime-lua 源码）：
--   * RimeSelectCandidate → Context::Select() → ConcreteEngine::OnSelect()
--     会无条件 seg.Close()，并把覆盖到输入串末尾的段标记 kConfirmed
--     （或 composition().Forward()）。也就是说「点候选」的语义就是
--     「把这个候选确认/上屏」，与候选 text 是不是空串无关，更与 Trime
--     版本无关。所以绝不能再把「按钮」伪装成候选。
--   * Segment.prompt 在 librime-lua 里可读可写（types.cc 的
--     SegmentReg.vars_set），Composition::GetPreedit() 把它插进编码行；
--     而 Composition::GetCommitText() 完全不含 prompt → 永不上屏。
--   * Trime 的 InputView 把 preedit.ui.root 放在键盘上方（above），
--     候选栏在键盘顶部 → 编码行与候选栏本来就是上下两行。
--   * 按键 send: F5~F10 经 KeyCode.parse → processKey 送进 Rime，
--     lua_processor 能收到 repr="F6"，且不会被 hookKeyboard 拦截。
-- ---------------------------------------------------------------------------

M.state = {
  code = "",       -- 当前规范化输入码
  seg = "",        -- 最后一个编码段（两键）
  list = nil,      -- 该段的同码音节列表
  index = 0,       -- 0 = 不选（混合候选），1..N = 选第 N 个音节
  syllable = nil,  -- 当前选中的音节
}

local function normalize(input)
  if not input then return "" end
  return (input:gsub("[ ']", ""))
end

function M.reset()
  local st = M.state
  st.code, st.seg, st.list = "", "", nil
  st.index, st.syllable = 0, nil
end

-- 返回「当前最后一段的同码音节列表, 规范化输入码」；不处于重码场景返回 nil。
function M.current_list(ctx)
  local bare = normalize(ctx and ctx.input)
  if bare == "" or (#bare % 2) ~= 0 or bare:match("[^a-z]") then
    return nil, bare
  end
  if ctx and ctx.get_option then
    local ok, ascii = pcall(function() return ctx:get_option("ascii_mode") end)
    if ok and ascii then return nil, bare end
  end
  local seg = bare:sub(-2)
  local list = M.by_code[seg]
  if not list or #list < 2 then return nil, bare end
  return list, bare
end

-- 落下选码状态。index=0 表示「全部 / 不选」。
function M.apply(ctx, index)
  local bare = normalize(ctx and ctx.input)
  local seg = (#bare >= 2) and bare:sub(-2) or ""
  local list = M.by_code[seg]
  local want, syllable = 0, nil
  if index > 0 and list and list[index] then
    want, syllable = index, list[index]
  end
  local st = M.state
  st.code, st.seg, st.list = bare, seg, list
  st.index, st.syllable = want, syllable
  return true
end

-- 让 Rime 重新翻译当前段（Context::RefreshNonConfirmedComposition）。
function M.refresh(ctx)
  if ctx and ctx.refresh_non_confirmed_composition then
    pcall(function() ctx:refresh_non_confirmed_composition() end)
  end
end

-- 把同码音节写进当前段的 prompt（候选栏上方那一行）。
function M.set_prompt(ctx, text)
  if not (ctx and ctx.composition) then return end
  pcall(function()
    local seg = ctx.composition:back()
    if seg then seg.prompt = text or "" end
  end)
end

return M
